"use client";

import React, { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { useParams, useRouter } from "next/navigation";
import {
  AlertTriangle,
  ArrowLeft,
  Check,
  CheckCircle2,
  HelpCircle,
  MessageSquareWarning,
  RefreshCw,
  ShieldCheck,
  Sparkles,
  UploadCloud,
  XCircle,
} from "lucide-react";
import { BeforeAfterCompare } from "@/components/evidence/BeforeAfterCompare";
import { PayPalButtonSlot } from "@/components/payments/PayPalButtonSlot";
import { PaymentLifecycleTimeline } from "@/components/payments/PaymentLifecycleTimeline";
import { AppShell } from "@/components/shell/AppShell";
import {
  Button,
  Card,
  Modal,
  PaymentStatusBadge,
  Skeleton,
  Textarea,
  WorkStatusBadge,
} from "@/components/ui/primitives";
import type {
  DecisionAction,
  Profile,
  Project,
  SystemConfigStatus,
  TaskBundle,
} from "@/lib/types";
import { formatDateTime, formatMoney } from "@/lib/utils";

export default function TaskInspectionPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();

  const [user, setUser] = useState<Profile | null>(null);
  const [config, setConfig] = useState<SystemConfigStatus | null>(null);
  const [task, setTask] = useState<TaskBundle | null>(null);
  const [project, setProject] = useState<Project | null>(null);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState<string | null>(null);
  const [uploadPct, setUploadPct] = useState<number | null>(null);
  const [banner, setBanner] = useState<{ text: string; ok: boolean } | null>(null);

  // Confirmation modal for homeowner decisions
  const [confirmDecision, setConfirmDecision] = useState<DecisionAction | null>(null);
  const [decisionReason, setDecisionReason] = useState("");

  const load = useCallback(async () => {
    try {
      const [meRes, taskRes] = await Promise.all([
        fetch("/api/auth/me", { cache: "no-store" }),
        fetch(`/api/tasks/${id}`, { cache: "no-store" }),
      ]);
      if (meRes.status === 401 || taskRes.status === 401) {
        router.push("/login");
        return;
      }
      const meJson = await meRes.json();
      const taskJson = await taskRes.json();
      if (!taskRes.ok) throw new Error(taskJson.error || "Failed to load task");
      setUser(meJson.user);
      setConfig(meJson.config);
      setTask(taskJson.task);
      setProject(taskJson.project);
    } catch (err) {
      setBanner({
        text: err instanceof Error ? err.message : "Failed to load task",
        ok: false,
      });
    } finally {
      setLoading(false);
    }
  }, [id, router]);

  useEffect(() => {
    load();
  }, [load]);

  function handleUpload(stage: "before" | "after", file: File) {
    if (!task) return;
    setBusy(`upload-${stage}`);
    setUploadPct(5);
    setBanner(null);
    const form = new FormData();
    form.append("stage", stage);
    form.append("file", file);
    const xhr = new XMLHttpRequest();
    xhr.open("POST", `/api/tasks/${task.id}/upload`);
    xhr.upload.onprogress = (ev) => {
      if (ev.lengthComputable) setUploadPct(Math.round((ev.loaded / ev.total) * 100));
    };
    xhr.onload = async () => {
      setUploadPct(null);
      setBusy(null);
      const data = (() => {
        try {
          return JSON.parse(xhr.responseText);
        } catch {
          return {};
        }
      })();
      if (xhr.status >= 200 && xhr.status < 300) {
        setBanner({ text: `${stage.toUpperCase()} photograph uploaded.`, ok: true });
        await load();
      } else {
        setBanner({ text: data.error || "Upload failed", ok: false });
      }
    };
    xhr.onerror = () => {
      setUploadPct(null);
      setBusy(null);
      setBanner({ text: "Network error uploading file", ok: false });
    };
    xhr.send(form);
  }

  async function runAIReview() {
    if (!task) return;
    setBusy("ai");
    setBanner(null);
    try {
      const res = await fetch(`/api/tasks/${task.id}/review`, { method: "POST" });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || "AI inspection failed");
      setBanner({
        text: `AI Inspection v${json.review.review_version} generated by ${json.review.model}.`,
        ok: true,
      });
      await load();
    } catch (err) {
      setBanner({
        text: err instanceof Error ? err.message : "AI inspection failed",
        ok: false,
      });
    } finally {
      setBusy(null);
    }
  }

  async function submitDecision() {
    if (!task || !confirmDecision) return;
    setBusy("decision");
    setBanner(null);
    try {
      const res = await fetch(`/api/tasks/${task.id}/decision`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ decision: confirmDecision, reason: decisionReason }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || "Settlement decision failed");
      setConfirmDecision(null);
      setDecisionReason("");
      const msg =
        confirmDecision === "accept"
          ? `PayPal Capture verified (${json.captureId || json.paypalStatus}).`
          : confirmDecision === "reject"
          ? `PayPal Authorization voided (${json.paypalStatus || "VOIDED"}).`
          : json.message || "Feedback sent to contractor.";
      setBanner({ text: msg, ok: true });
      await load();
    } catch (err) {
      setConfirmDecision(null);
      setBanner({
        text: err instanceof Error ? err.message : "Decision failed",
        ok: false,
      });
      await load();
    } finally {
      setBusy(null);
    }
  }

  async function reconcilePayment() {
    if (!task) return;
    setBusy("reconcile");
    setBanner(null);
    try {
      const res = await fetch(`/api/tasks/${task.id}/reconcile`, { method: "POST" });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error || "Reconcile failed");
      setBanner({ text: json.message || "Status reconciled with PayPal.", ok: true });
      await load();
    } catch (err) {
      setBanner({
        text: err instanceof Error ? err.message : "Reconcile failed",
        ok: false,
      });
    } finally {
      setBusy(null);
    }
  }

  if (loading || !user || !config) {
    return (
      <div className="min-h-screen bg-slate-50 p-8 max-w-6xl mx-auto space-y-4">
        <Skeleton className="h-10 w-64" />
        <Skeleton className="h-96 w-full" />
      </div>
    );
  }

  if (!task || !project) {
    return (
      <AppShell user={user} config={config}>
        <Card className="p-8 text-center">
          <p className="text-sm font-semibold text-slate-900">Task not found</p>
        </Card>
      </AppShell>
    );
  }

  const before = task.evidence.find((e) => e.evidence_type === "before") || null;
  const after = task.evidence.find((e) => e.evidence_type === "after") || null;
  const findings = task.latest_review?.structured_findings;
  const isSettled = ["CAPTURED", "VOIDED", "AUTHORIZATION_EXPIRED"].includes(
    task.payment_status
  );
  const canHomeownerDecide =
    user.role === "homeowner" &&
    ["EVIDENCE_SUBMITTED", "AI_REVIEWED", "CORRECTIONS_REQUESTED"].includes(
      task.work_status
    ) &&
    ["AUTHORIZED", "SETTLEMENT_PENDING", "PAYMENT_FAILED"].includes(task.payment_status);

  const canAuthorize =
    user.role === "homeowner" &&
    ["DRAFT", "ORDER_CREATED", "BUYER_APPROVAL_PENDING", "PAYMENT_FAILED"].includes(
      task.payment_status
    );

  return (
    <AppShell user={user} config={config}>
      <div className="space-y-6">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <Link
            href={`/projects/${project.id}`}
            className="inline-flex items-center gap-1.5 text-xs font-medium text-slate-600 hover:text-slate-900"
          >
            <ArrowLeft className="h-3.5 w-3.5" />
            Back to {project.title}
          </Link>
          <div className="flex items-center gap-2">
            {task.payment.paypal_order_id && (
              <Button
                size="sm"
                variant="outline"
                disabled={busy === "reconcile"}
                onClick={reconcilePayment}
              >
                <RefreshCw
                  className={`h-3.5 w-3.5 ${busy === "reconcile" ? "animate-spin" : ""}`}
                />
                Reconcile with PayPal
              </Button>
            )}
          </div>
        </div>

        {banner && (
          <div
            role="status"
            className={`rounded-xl border px-4 py-3 text-xs ${
              banner.ok
                ? "border-emerald-200 bg-emerald-50 text-emerald-800"
                : "border-red-200 bg-red-50 text-red-700"
            }`}
          >
            {banner.text}
          </div>
        )}

        {/* Header & Payment Lifecycle */}
        <Card className="p-6 space-y-5">
          <div className="flex flex-wrap items-start justify-between gap-4">
            <div>
              <p className="text-xs font-medium text-slate-500">
                {project.title} · {project.location}
              </p>
              <h1 className="text-2xl font-bold text-slate-900 mt-0.5">{task.title}</h1>
              <p className="mt-1 text-sm text-slate-600 max-w-2xl">{task.description}</p>
              <div className="mt-3 flex flex-wrap gap-2">
                <PaymentStatusBadge status={task.payment_status} />
                <WorkStatusBadge status={task.work_status} />
              </div>
            </div>
            <div className="text-right">
              <p className="font-mono-code text-2xl font-bold text-slate-900 tabular-nums">
                {formatMoney(task.amount_minor_units)}
              </p>
              <p className="text-xs text-slate-500">Independent PayPal Authorization</p>
            </div>
          </div>

          <PaymentLifecycleTimeline payment={task.payment} />

          {canAuthorize && (
            <div className="rounded-xl border border-blue-200 bg-blue-50/50 p-4 space-y-2">
              <p className="text-xs font-semibold text-slate-900">
                Step 1 · Authorize {formatMoney(task.amount_minor_units)} Hold via PayPal
              </p>
              <PayPalButtonSlot
                clientId={config.paypal.clientId}
                configured={config.paypal.configured}
                taskId={task.id}
                amountFormatted={formatMoney(task.amount_minor_units)}
                onStatusMessage={(text, ok) => setBanner({ text, ok })}
                onSuccess={load}
              />
            </div>
          )}
        </Card>

        {/* Split Inspection View */}
        <div className="grid grid-cols-1 gap-6 lg:grid-cols-12">
          {/* Left: Evidence & Comparison */}
          <div className="lg:col-span-6 space-y-5">
            <Card className="p-5 space-y-4">
              <div className="flex items-center justify-between">
                <h2 className="text-base font-semibold text-slate-900">
                  Submitted Repair Evidence
                </h2>
                <span className="text-xs text-slate-500">
                  {task.evidence.length} file(s)
                </span>
              </div>

              <BeforeAfterCompare
                taskId={task.id}
                before={before}
                after={after}
                allEvidence={task.evidence}
                annotations={task.annotations}
                canAnnotate={!isSettled}
                onAnnotationChange={load}
              />

              {user.role === "contractor" && !isSettled && (
                <div className="grid grid-cols-2 gap-3 pt-2">
                  {(["before", "after"] as const).map((stage) => (
                    <label
                      key={stage}
                      className="flex flex-col items-center justify-center rounded-xl border border-dashed border-slate-300 bg-slate-50 p-3 text-center hover:border-blue-500 cursor-pointer"
                    >
                      <UploadCloud className="h-4 w-4 text-blue-600" />
                      <span className="mt-1 text-xs font-medium capitalize text-slate-800">
                        Upload {stage}
                      </span>
                      <input
                        type="file"
                        accept="image/jpeg,image/png,image/webp"
                        className="hidden"
                        onChange={(e) => {
                          const f = e.target.files?.[0];
                          if (f) handleUpload(stage, f);
                          e.target.value = "";
                        }}
                      />
                    </label>
                  ))}
                </div>
              )}

              {uploadPct !== null && (
                <div className="h-2 w-full overflow-hidden rounded-full bg-slate-200">
                  <div
                    className="h-full bg-blue-600 transition-all"
                    style={{ width: `${uploadPct}%` }}
                  />
                </div>
              )}

              {task.contractor_notes && (
                <div className="rounded-xl border border-slate-200 bg-slate-50 p-3 text-xs text-slate-700">
                  <strong>Contractor Notes:</strong> {task.contractor_notes}
                </div>
              )}

              <div className="rounded-xl border border-slate-200 bg-slate-50 p-3.5">
                <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500 mb-1.5">
                  Agreed Acceptance Criteria
                </p>
                <ul className="list-disc pl-4 text-xs text-slate-700 space-y-1">
                  {task.acceptance_criteria.map((c, i) => (
                    <li key={i}>{c}</li>
                  ))}
                </ul>
              </div>
            </Card>
          </div>

          {/* Right: Structured AI Report & Homeowner Controls */}
          <div className="lg:col-span-6 space-y-5">
            <Card className="p-5 space-y-4">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <div>
                  <h2 className="text-base font-semibold text-slate-900">
                    AI Evidence Inspection
                  </h2>
                  <p className="text-xs text-slate-500">
                    Advisory analysis only — AI never authorizes, captures, or voids funds.
                  </p>
                </div>
                <Button
                  size="sm"
                  variant="outline"
                  disabled={busy === "ai" || !before || !after}
                  onClick={runAIReview}
                >
                  <Sparkles className="h-3.5 w-3.5 text-blue-600" />
                  {busy === "ai"
                    ? "Inspecting Photos..."
                    : findings
                    ? "Re-run Inspection"
                    : "Run AI Inspection"}
                </Button>
              </div>

              {!config.ai.configured && (
                <div className="rounded-xl border border-amber-200 bg-amber-50 p-3 text-xs text-amber-900">
                  <strong>AI Provider Not Configured:</strong> Add <code>GEMINI_API_KEY</code>{" "}
                  or <code>ANTHROPIC_API_KEY</code> in <code>.env.local</code> to generate live
                  multimodal inspections. No canned reports are substituted.
                </div>
              )}

              {findings ? (
                <div className="space-y-4 text-xs">
                  <div
                    className={`rounded-xl border p-4 ${
                      findings.overall_assessment === "appears_satisfied"
                        ? "border-emerald-200 bg-emerald-50/70 text-emerald-950"
                        : findings.overall_assessment === "concerns_identified"
                        ? "border-red-200 bg-red-50/70 text-red-950"
                        : "border-amber-200 bg-amber-50/70 text-amber-950"
                    }`}
                  >
                    <div className="flex items-center justify-between gap-2">
                      <span className="inline-flex items-center gap-1.5 font-bold uppercase tracking-wide">
                        {findings.overall_assessment === "appears_satisfied" ? (
                          <CheckCircle2 className="h-4 w-4 text-emerald-600" />
                        ) : findings.overall_assessment === "concerns_identified" ? (
                          <AlertTriangle className="h-4 w-4 text-red-600" />
                        ) : (
                          <HelpCircle className="h-4 w-4 text-amber-600" />
                        )}
                        {findings.overall_assessment.replaceAll("_", " ")}
                      </span>
                      <span className="font-mono-code text-[11px] opacity-80">
                        v{task.latest_review?.review_version} · {task.latest_review?.model}
                      </span>
                    </div>
                    <p className="mt-2 leading-relaxed">{findings.summary}</p>
                    <p className="mt-1.5 font-medium">
                      Suggested outcome:{" "}
                      <span className="underline">
                        {findings.suggested_outcome.replaceAll("_", " ")}
                      </span>{" "}
                      · Views comparable: {findings.views_comparable}
                    </p>
                  </div>

                  <div>
                    <h3 className="font-semibold text-slate-900 mb-2">
                      Evidence Checklist
                    </h3>
                    <ul className="space-y-2">
                      {findings.criteria_checks.map((c, idx) => (
                        <li
                          key={idx}
                          className="rounded-lg border border-slate-200 bg-slate-50 p-2.5 flex items-start gap-2.5"
                        >
                          {c.status === "satisfied" ? (
                            <Check className="h-4 w-4 text-emerald-600 shrink-0 mt-0.5" />
                          ) : c.status === "unmet" ? (
                            <XCircle className="h-4 w-4 text-red-600 shrink-0 mt-0.5" />
                          ) : (
                            <HelpCircle className="h-4 w-4 text-amber-600 shrink-0 mt-0.5" />
                          )}
                          <div>
                            <p className="font-semibold text-slate-900">{c.criterion}</p>
                            <p className="text-slate-600 mt-0.5">{c.observation}</p>
                          </div>
                        </li>
                      ))}
                    </ul>
                  </div>

                  <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
                    <div className="rounded-lg border border-slate-200 p-3">
                      <p className="font-semibold text-slate-900 mb-1">
                        Visible Observations
                      </p>
                      <ul className="list-disc pl-4 space-y-0.5 text-slate-600">
                        {findings.visible_observations.map((o, i) => (
                          <li key={i}>{o}</li>
                        ))}
                      </ul>
                    </div>
                    <div className="rounded-lg border border-amber-200 bg-amber-50/50 p-3">
                      <p className="font-semibold text-amber-950 mb-1">
                        Limitations &amp; Uncertainty
                      </p>
                      <ul className="list-disc pl-4 space-y-0.5 text-amber-900">
                        {findings.limitations_and_uncertainty.map((u, i) => (
                          <li key={i}>{u}</li>
                        ))}
                      </ul>
                    </div>
                  </div>

                  {findings.missing_evidence.length > 0 && (
                    <div className="rounded-lg border border-slate-200 bg-slate-50 p-3">
                      <p className="font-semibold text-slate-900 mb-1">Missing Evidence</p>
                      <ul className="list-disc pl-4 text-slate-600">
                        {findings.missing_evidence.map((m, i) => (
                          <li key={i}>{m}</li>
                        ))}
                      </ul>
                    </div>
                  )}

                  <div className="rounded-lg border border-slate-200 bg-slate-50 p-3">
                    <p className="font-semibold text-slate-900 mb-1">
                      Recommended Next Steps
                    </p>
                    <ul className="list-disc pl-4 text-slate-600">
                      {findings.recommended_next_steps.map((s, i) => (
                        <li key={i}>{s}</li>
                      ))}
                    </ul>
                  </div>
                </div>
              ) : (
                <p className="text-xs text-slate-500 py-4 text-center border border-dashed border-slate-200 rounded-xl">
                  {before && after
                    ? "Both before and after photos are ready. Click 'Run AI Inspection' to evaluate against criteria."
                    : "Waiting for contractor to upload both BEFORE and AFTER photographs."}
                </p>
              )}
            </Card>

            {/* Homeowner Settlement Decision */}
            <Card className="p-5 space-y-4">
              <div className="flex items-center justify-between">
                <h2 className="text-base font-semibold text-slate-900">
                  Homeowner Settlement Decision
                </h2>
                <ShieldCheck className="h-4 w-4 text-blue-600" />
              </div>

              {task.payment_status === "CAPTURED" ? (
                <div className="rounded-xl border border-emerald-200 bg-emerald-50 p-4 space-y-1">
                  <p className="text-sm font-bold text-emerald-900">
                    Accepted · {formatMoney(task.amount_minor_units)} Captured via PayPal
                  </p>
                  <p className="font-mono-code text-xs text-emerald-800">
                    Capture ID: {task.payment.paypal_capture_id} · Status:{" "}
                    {task.payment.paypal_status}
                  </p>
                </div>
              ) : task.payment_status === "VOIDED" ? (
                <div className="rounded-xl border border-slate-300 bg-slate-100 p-4 space-y-1">
                  <p className="text-sm font-bold text-slate-900">
                    Rejected · {formatMoney(task.amount_minor_units)} Authorization Voided
                  </p>
                  <p className="font-mono-code text-xs text-slate-600">
                    Auth ID: {task.payment.paypal_authorization_id} · Status:{" "}
                    {task.payment.paypal_status} (Uncaptured hold cancelled; no funds moved)
                  </p>
                </div>
              ) : canHomeownerDecide ? (
                <div className="space-y-3">
                  <div className="grid grid-cols-1 gap-2.5 sm:grid-cols-2">
                    <Button
                      variant="success"
                      size="lg"
                      onClick={() => setConfirmDecision("accept")}
                    >
                      <CheckCircle2 className="h-4 w-4" />
                      Accept &amp; Capture {formatMoney(task.amount_minor_units)}
                    </Button>
                    <Button
                      variant="danger"
                      size="lg"
                      onClick={() => setConfirmDecision("reject")}
                    >
                      <XCircle className="h-4 w-4" />
                      Reject &amp; Void Hold
                    </Button>
                  </div>
                  <div className="grid grid-cols-1 gap-2 sm:grid-cols-2">
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => setConfirmDecision("request_corrections")}
                    >
                      <MessageSquareWarning className="h-3.5 w-3.5" />
                      Request Corrections
                    </Button>
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => setConfirmDecision("request_evidence")}
                    >
                      Request Additional Evidence
                    </Button>
                  </div>
                  <p className="text-[11px] text-slate-500">
                    Requesting corrections or extra evidence notifies the contractor while
                    keeping the PayPal hold intact. Accepting calls PayPal Capture; rejecting
                    calls PayPal Void.
                  </p>
                </div>
              ) : (
                <p className="text-xs text-slate-500">
                  {user.role === "contractor"
                    ? "Only the homeowner can accept, capture, reject, or void this payment."
                    : !task.payment.paypal_authorization_id
                    ? "Authorize the PayPal hold first before settling."
                    : "Decision controls unlock once the contractor uploads before and after evidence."}
                </p>
              )}

              {/* Audit Timeline */}
              <div className="border-t border-slate-100 pt-4">
                <h3 className="text-xs font-semibold uppercase tracking-wider text-slate-500 mb-3">
                  Audit &amp; Payment Events
                </h3>
                <ol className="space-y-2.5 border-l border-slate-200 pl-4">
                  {task.events.map((ev) => (
                    <li key={ev.id} className="relative text-xs">
                      <span className="absolute -left-[21px] top-1 h-2 w-2 rounded-full bg-slate-400" />
                      <p className="font-medium text-slate-800">
                        {ev.event_type.replaceAll("_", " ")}
                      </p>
                      <p className="text-[11px] text-slate-500">
                        {ev.actor} · {formatDateTime(ev.created_at)}
                      </p>
                    </li>
                  ))}
                </ol>
              </div>
            </Card>
          </div>
        </div>
      </div>

      {/* Confirmation Dialog */}
      <Modal
        open={Boolean(confirmDecision)}
        onClose={() => !busy && setConfirmDecision(null)}
        title={
          confirmDecision === "accept"
            ? "Confirm PayPal Payment Capture"
            : confirmDecision === "reject"
            ? "Confirm PayPal Authorization Void"
            : "Send Feedback to Contractor"
        }
        description={
          confirmDecision === "accept"
            ? `You're about to capture ${formatMoney(task.amount_minor_units)} for ${task.title} using existing PayPal authorization ${task.payment.paypal_authorization_id}.`
            : confirmDecision === "reject"
            ? `You're about to void the ${formatMoney(task.amount_minor_units)} authorization (${task.payment.paypal_authorization_id}) for ${task.title}. Voiding cancels the uncaptured hold subject to PayPal processing and does not claim a refund.`
            : "Your feedback will be recorded and visible to the contractor. The PayPal authorization stays open."
        }
      >
        <div className="space-y-4">
          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              Decision Note / Reason (optional)
            </label>
            <Textarea
              rows={3}
              value={decisionReason}
              onChange={(e) => setDecisionReason(e.target.value)}
              placeholder={
                confirmDecision === "accept"
                  ? "Work satisfies all agreed criteria."
                  : "Describe what remains unresolved or needs correction..."
              }
            />
          </div>
          <div className="flex justify-end gap-2">
            <Button
              variant="outline"
              disabled={busy === "decision"}
              onClick={() => setConfirmDecision(null)}
            >
              Cancel
            </Button>
            <Button
              variant={
                confirmDecision === "accept"
                  ? "success"
                  : confirmDecision === "reject"
                  ? "danger"
                  : "primary"
              }
              disabled={busy === "decision"}
              onClick={submitDecision}
            >
              {busy === "decision"
                ? "Verifying with PayPal..."
                : confirmDecision === "accept"
                ? `Capture ${formatMoney(task.amount_minor_units)}`
                : confirmDecision === "reject"
                ? "Void Authorization"
                : "Send to Contractor"}
            </Button>
          </div>
        </div>
      </Modal>
    </AppShell>
  );
}
